#!/usr/bin/env python3
"""Write reports/backlinks.md: who links to whom across all skills, with the relation type.

Relation types: see / uses / implements / depends_on (frontmatter fields), body (wikilink in the
text), and requires (note -> skill dependency). Also lists orphans (notes nobody links to) and
skill-level dependencies.

Usage: python tools/backlinks.py
"""
import sys
from collections import defaultdict
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from notes_lib import (REPORTS_DIR, RELATION_FIELDS, as_list, load_notes,  # noqa: E402
                       wikilinks)


def main():
    notes = load_notes()
    by_id = {n['fm'].get('id'): n for n in notes if n['fm'].get('id')}
    incoming = defaultdict(lambda: defaultdict(set))   # target -> source -> {types}
    outgoing = defaultdict(int)
    skill_deps = defaultdict(set)
    for n in notes:
        src = n['fm'].get('id')
        if not src:
            continue
        typed = set()
        for field in RELATION_FIELDS:
            for item in as_list(n['fm'].get(field)):
                for t in wikilinks(str(item)):
                    incoming[t][src].add(field)
                    typed.add(t)
        for t in set(wikilinks(n['body'])):
            incoming[t][src].add('body')
        outgoing[src] = len(typed | set(wikilinks(n['body'])))
        for skill in as_list(n['fm'].get('requires')):
            skill_deps[n['skill']].add(str(skill))

    lines = ['# Backlinks', '', '> Generated by `python tools/backlinks.py` — do not edit by hand.',
             '> Types: `see`/`uses`/`implements`/`depends_on` = frontmatter relation, `body` = wikilink in the text.', '']
    skills = sorted({n['skill'] for n in notes})
    total_edges = sum(len(v) for v in incoming.values())
    lines += [f'Notes: {len(by_id)} · skills: {len(skills)} · linked pairs: {total_edges}', '']
    lines += ['## Skill dependencies (`requires`)', '']
    for s in skills:
        deps = ', '.join(sorted(skill_deps[s])) or '—'
        lines.append(f'- `{s}` → {deps}')
    orphans = sorted(i for i in by_id if not incoming.get(i))
    lines += ['', f'## Orphans ({len(orphans)}) — no incoming links', '']
    lines += [f'- [[{o}]]' for o in orphans] or ['- none']
    for s in skills:
        lines += ['', f'## {s}', '', '| Note | In | Out | Linked from (types) |', '|---|---|---|---|']
        ids = sorted(i for i, n in by_id.items() if n['skill'] == s)
        for i in ids:
            srcs = incoming.get(i, {})
            cell = ' · '.join(f'[[{src}]] ({"/".join(sorted(types))})' for src, types in sorted(srcs.items()))
            lines.append(f'| [[{i}]] | {len(srcs)} | {outgoing[i]} | {cell or "—"} |')
    out = REPORTS_DIR / 'backlinks.md'
    out.write_text('\n'.join(lines) + '\n', encoding='utf-8', newline='\n')
    print(f'{out.relative_to(REPORTS_DIR.parent)}: {len(by_id)} notes, {total_edges} linked pairs, '
          f'{len(orphans)} orphans')
    return 0


if __name__ == '__main__':
    sys.exit(main())
