#!/usr/bin/env python3
"""Generate the 2-level index for every skill.

Level 1: the areas table inside skills/<skill>/SKILL.md, between <!-- INDEX:START --> and <!-- INDEX:END -->.
Level 2: one _index.md per area folder (id | summary | path), paths relative to the skill root.

Optional skills/<skill>/areas.yaml maps area -> one-line description (and sets the display order).
Notes are grouped by their `area` frontmatter (fallback: parent folder) and sorted by
(`order` frontmatter if present, id).

Usage: python tools/build_index.py [--check] [skill ...]
  --check  do not write; exit 1 if any generated file is out of date.
"""
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from notes_lib import discover_skills, load_notes, parse_yaml_subset  # noqa: E402

START, END = '<!-- INDEX:START -->', '<!-- INDEX:END -->'
GENERATED = '<!-- generated by tools/build_index.py — do not edit by hand -->'


def load_area_descriptions(skill_path):
    f = skill_path / 'areas.yaml'
    if not f.exists():
        return {}
    raw = f.read_text(encoding='utf-8')
    try:
        import yaml
        data = yaml.safe_load(raw) or {}
    except ImportError:
        data = parse_yaml_subset(raw)
    return {str(k): str(v) for k, v in data.items()}


def cell(s):
    return str(s).replace('|', '\\|').replace('\n', ' ').strip()


def build_skill(skill, skill_path, notes):
    """Return {path: new_content} for one skill."""
    desc = load_area_descriptions(skill_path)
    areas = {}
    for n in notes:
        area = n['fm'].get('area') or n['path'].parent.name
        areas.setdefault(area, []).append(n)
    order = list(desc) + sorted(a for a in areas if a not in desc)
    outputs, rows = {}, []
    for area in order:
        if area not in areas:
            continue
        items = sorted(areas[area], key=lambda n: (n['fm'].get('order', 1000), n['fm'].get('id', '')))
        folders = {n['path'].parent for n in items}
        folder = sorted(folders)[0] if len(folders) == 1 else items[0]['path'].parent
        index_path = folder / '_index.md'
        index_rel = index_path.relative_to(skill_path).as_posix()
        covers = desc.get(area, ' · '.join(n['fm'].get('title', '') for n in items[:4]))
        lines = [f'# {area} — {skill}', '', GENERATED,
                 f'{cell(covers)}. Paths are relative to the skill root (`skills/{skill}/`).', '',
                 '| id | summary | path |', '|---|---|---|']
        for n in items:
            lines.append(f"| [[{n['fm'].get('id', '?')}]] | {cell(n['fm'].get('summary', ''))} | {n['rel']} |")
        outputs[index_path] = '\n'.join(lines) + '\n'
        rows.append(f'| {area} | {len(items)} | `{index_rel}` | {cell(covers)} |')
    skill_md = skill_path / 'SKILL.md'
    text = skill_md.read_text(encoding='utf-8')
    if START not in text or END not in text:
        raise SystemExit(f'{skill_md}: missing {START} / {END} markers')
    block = '\n'.join([START, GENERATED, '| Area | Notes | Open | Covers |', '|---|---|---|---|', *rows, END])
    head, rest = text.split(START, 1)
    tail = rest.split(END, 1)[1]
    outputs[skill_md] = head + block + tail
    return outputs


def main(argv):
    check = '--check' in argv
    wanted = [a for a in argv if not a.startswith('--')]
    skills = discover_skills()
    if wanted:
        missing = [w for w in wanted if w not in skills]
        if missing:
            raise SystemExit(f'unknown skill(s): {", ".join(missing)}; found: {", ".join(skills)}')
        skills = {k: v for k, v in skills.items() if k in wanted}
    all_notes = load_notes()
    stale = []
    for skill, spath in skills.items():
        outputs = build_skill(skill, spath, [n for n in all_notes if n['skill'] == skill])
        for path, content in outputs.items():
            old = path.read_text(encoding='utf-8') if path.exists() else None
            if old == content:
                continue
            stale.append(path)
            if not check:
                path.write_text(content, encoding='utf-8', newline='\n')
        n_notes = sum(1 for n in all_notes if n['skill'] == skill)
        print(f'{skill}: {n_notes} notes, {len(outputs) - 1} area indexes')
    if check and stale:
        print('out of date:\n  ' + '\n  '.join(str(p) for p in stale))
        return 1
    print(('up to date' if check else f'written {len(stale)} file(s)'))
    return 0


if __name__ == '__main__':
    sys.exit(main(sys.argv[1:]))
